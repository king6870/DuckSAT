/**
 * Unified Question Generator Service
 * 
 * This service consolidates all question generation logic into a single, production-ready service.
 * It combines the clean architecture of CLEAN's implementation with the production features
 * from Migration's aiQuestionService.
 * 
 * Key Features:
 * - 6-step pipeline: Initialize → Generate → Evaluate → Retry → Validate → Store
 * - Quality retry logic: Up to 5 retries for questions below 80% quality threshold
 * - Diagram consistency validation: -40% penalty for missing diagrams
 * - Dynamic endpoint configuration: Supports multiple Azure OpenAI endpoints
 * - Comprehensive error handling and logging
 * 
 * Architecture: Based on ADR-47 and SPEC-47
 * Epic: #46, Feature: #47, Story: #51
 */

import { PrismaClient } from '@prisma/client'
import { getAllSubtopics, type SATSubtopic } from '@/data/sat-topics'
import { buildMathQuestionsPrompt, buildReadingQuestionsPrompt } from './questionPromptTemplates'
