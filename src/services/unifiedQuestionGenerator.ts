  /**
   * Store questions in database (with image generation)
   */
  private async storeQuestions(questions: EvaluatedQuestion[]): Promise<void> {
    console.log(`💾 Storing ${questions.length} questions in database...`)

    // First, generate images for questions that need them
    const questionsWithImages = await this.generateAndStoreImages(questions)

    const dbSubtopics = await this.prisma.subtopic.findMany({
      select: {
        id: true,
        name: true,
        topic: {
          select: {
            name: true
          }
        }
      }
    })

    const dbTopics = await this.prisma.topic.findMany({
      where: { isActive: true },
      select: {
        id: true,
        name: true,
        moduleType: true
      }
    })

    const subtopicMap = new Map(
      dbSubtopics.map((subtopic) => [this.normalizeSubtopicKey(subtopic.name), subtopic])
    )

    // Then store in database
    for (const question of questionsWithImages) {
      try {
        const questionSubtopicKey = this.normalizeSubtopicKey(question.subtopic)

        let matchedSubtopic = subtopicMap.get(questionSubtopicKey)

        if (!matchedSubtopic) {
          matchedSubtopic = dbSubtopics.find((subtopic) => {
            const dbKey = this.normalizeSubtopicKey(subtopic.name)
            return dbKey.includes(questionSubtopicKey) || questionSubtopicKey.includes(dbKey)
          })
        }

        if (!matchedSubtopic) {
          const normalizedSubtopic = this.normalizeSubtopicKey(question.subtopic || '')
          const moduleTopics = dbTopics.filter(topic => topic.moduleType === question.moduleType)

          const matchedTopic = moduleTopics.find(topic => this.normalizeSubtopicKey(topic.name) === normalizedSubtopic)
            || moduleTopics.find(topic => {
              const topicKey = this.normalizeSubtopicKey(topic.name)
              return topicKey.includes(normalizedSubtopic) || normalizedSubtopic.includes(topicKey)
            })
            || moduleTopics[0]

          if (matchedTopic) {
            const created = await this.prisma.subtopic.create({
              data: {
                topicId: matchedTopic.id,
                name: question.subtopic,
                description: `Auto-created from unified generator (${question.moduleType})`,
                targetQuestions: 100,
                currentCount: 0,
                isActive: true
              },
              select: {
                id: true,
                name: true,
                topic: {
                  select: {
                    name: true
                  }
                }
              }
            })

            matchedSubtopic = created
            subtopicMap.set(questionSubtopicKey, created)
            console.log(`  🆕 Created missing subtopic in DB: ${question.subtopic} (topic: ${matchedTopic.name})`)
          } else {
            console.warn(`  ⚠️  Subtopic not found in DB and no topic available: ${question.subtopic}, storing with null subtopicId`)
          }
        }

        const derivedCategory = this.deriveDrillCategory(
          question.moduleType,
          matchedSubtopic?.topic.name,
          matchedSubtopic?.name || question.subtopic
        )

        await this.prisma.question.create({
          data: {
            question: question.question,
            options: JSON.stringify(question.options),
            correctAnswer: question.correctAnswer,
            explanation: question.explanation,
            moduleType: question.moduleType,
            difficulty: question.difficulty,
            subtopicId: matchedSubtopic?.id || null,
            category: derivedCategory,
            subtopic: question.subtopic,
            chartData: question.hasChart ? JSON.stringify({
              description: question.chartDescription,
              graphType: question.graphType,
              hasChart: true
            }) : null,
            imageUrl: question.imageUrl || null,
            imageAlt: question.imageAlt || null,
            passage: question.passage || null,
            reviewStatus: question.isAccepted ? 'approved' : 'pending',
            reviewComments: `Quality score: ${(question.qualityScore * 100).toFixed(1)}%`,
            timeEstimate: 90, // Default 90 seconds
            source: 'AI Generated (Unified Service)',
            tags: JSON.stringify([question.moduleType, question.difficulty, question.subtopic]),
            isActive: true
          }
        })

        console.log(`  ✅ Stored: ${question.subtopic} (${(question.qualityScore * 100).toFixed(0)}% quality)`)
      } catch (error) {
        console.error(`  ❌ Failed to store question:`, error)
      }
    }

    console.log(`✅ Database storage complete`)
  }

  /**
   * Generate and store images for questions with chart descriptions
   */
  private async generateAndStoreImages(questions: EvaluatedQuestion[]): Promise<EvaluatedQuestion[]> {
    const questionsWithCharts = questions.filter(
      q => q.hasChart && q.chartDescription && q.moduleType === 'math'
    )

    console.log(`🎨 Generating images for ${questionsWithCharts.length} questions with charts...`)

    if (questionsWithCharts.length === 0) {
      return questions
    }

    // Dynamically import image service
    const { imageGenerationService } = await import('./imageGenerationService')

    const questionsWithImages = await Promise.all(
      questions.map(async (question) => {
        if (question.hasChart && question.chartDescription && question.moduleType === 'math') {
          try {
            console.log(`  🎨 Generating image for: "${question.question.substring(0, 50)}..."`)

            const chartConfig = {
              type: (question.graphType as 'coordinate-plane' | 'bar-chart' | 'scatter-plot' | 'box-plot' | 'geometric-diagram' | 'function-graph') || 'coordinate-plane',
              description: question.chartDescription,
              width: 600,
              height: 400
            }

            // Try DALL-E first
            let imageUrl = await imageGenerationService.generateChartImage(chartConfig)

            // Fallback to SVG if DALL-E fails
            if (!imageUrl) {
              console.log('    📋 DALL-E failed, generating SVG fallback...')
              imageUrl = await imageGenerationService.generateSVGChart(chartConfig)
            }

            if (imageUrl) {
              console.log(`    ✅ Image generated: ${imageUrl.substring(0, 80)}...`)
              return {
                ...question,
                imageUrl,
                imageAlt: question.chartDescription
              }
            } else {
              console.error(`    ❌ Image generation failed`)
              return question
            }
          } catch (error) {
            console.error('    ❌ Image generation error:', error)
            return question
          }
        }

        return question
      })
    )

    const successCount = questionsWithImages.filter(q => q.imageUrl).length
    console.log(`✅ Image generation complete: ${successCount}/${questionsWithCharts.length} successful`)

    return questionsWithImages
  }
