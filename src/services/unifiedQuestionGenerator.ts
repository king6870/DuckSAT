// TYPES & INTERFACES
// ============================================================================

// Enriched subtopic type returned by getAllSubtopics()
type EnrichedSubtopic = SATSubtopic & { topicId: string; topicName: string; moduleType: 'reading-writing' | 'math' }

/**
 * Quality thresholds for question acceptance and regeneration
 */
const QUALITY_THRESHOLDS = {
  REGENERATION_THRESHOLD: 0.80, // Regenerate if quality ≤80%
  MAX_REGENERATION_ATTEMPTS: 5,  // Max 5 retries per question
  MIN_ACCEPTABLE_QUALITY: 0.70   // Absolute minimum to store
} as const

const READING_PASSAGE_OMISSION_MARKER = /\.\.\.|…|\[omitted\]|\(omitted\)|\[excerpt\]|abridged|truncated/i

const FULL_PASSAGE_SUBTOPICS = new Set([
  'reading comprehension',
  'main ideas and central claims',
  'supporting details and evidence',
  'inferences and implications',
  'vocabulary in context',
  'text structure and organization',
  'author s purpose and point of view',
  'authors purpose and point of view',
  'comparing texts and viewpoints',
])

/**
 * Raw question generated by LLM (before evaluation)
 */
export interface GeneratedQuestion {
  question: string
  options: string[]
  correctAnswer: number // Index of correct answer (0-based)
  explanation: string
  subtopic: string
  moduleType: 'math' | 'reading-writing'
  hasChart: boolean
  chartDescription?: string
  graphType?: string
  passage?: string
  passageTitle?: string
  passageAuthor?: string
}

/**
 * Question after Grok evaluation (adds quality metrics)
 */
export interface EvaluatedQuestion extends GeneratedQuestion {
  difficulty: 'easy' | 'medium' | 'hard'
  qualityScore: number
  isAccepted: boolean
  evaluationFeedback: string
  imageUrl?: string
  imageAlt?: string
}

/**
 * Options for question generation
 */
export interface GenerationOptions {
  mathCount?: number
  readingCount?: number
  specificTopics?: string[]
  specificSubtopics?: string[]
  specializedMode?: boolean
  moduleType?: 'math' | 'reading-writing' | 'both'
  difficulty?: 'easy' | 'medium' | 'hard' | 'mixed'
  includeImages?: boolean
  includePassages?: boolean
  storeInDatabase?: boolean
  temperature?: number
  maxTokens?: number
  enableRetry?: boolean
  enableValidation?: boolean
  skipEvaluation?: boolean
}

/**
 * Result returned by generateQuestions()
 */
export interface GenerationResult {
  questions: EvaluatedQuestion[]
  summary: {
    total: number
    accepted: number
    rejected: number
    mathCount: number
    readingCount: number
    avgQuality: number
    retryCount: number
    validationErrors: number
  }
}

/**
 * Deterministic generation plan used before LLM calls
 */
export interface GenerationPlan {
  options: Required<Pick<GenerationOptions,
    'mathCount' |
    'readingCount' |
    'moduleType' |
    'specializedMode' |
    'includeImages' |
    'includePassages' |
    'storeInDatabase' |
    'temperature' |
    'maxTokens' |
    'enableRetry' |
    'enableValidation'
  >> & Omit<GenerationOptions,
    'mathCount' |
    'readingCount' |
    'moduleType' |
    'specializedMode' |
    'includeImages' |
    'includePassages' |
    'storeInDatabase' |
    'temperature' |
    'maxTokens' |
    'enableRetry' |
    'enableValidation'
  >
  mathSubtopics: EnrichedSubtopic[]
  readingSubtopics: EnrichedSubtopic[]
}

