  /**
   * Validate diagram consistency: -40% penalty for questions mentioning diagrams without images
   */
  private async validateDiagramConsistency(questions: EvaluatedQuestion[]): Promise<EvaluatedQuestion[]> {
    console.log('🔍 Validating diagram consistency...')

    return questions.map(question => {
      // Only validate math questions
      if (question.moduleType !== 'math') {
        return question
      }

      const questionLower = question.question.toLowerCase()
      
      // More precise detection: look for phrases that indicate visual elements
      const diagramPhrases = [
        'in the diagram',
        'in the chart',
        'in the graph',
        'in the figure',
        'the diagram',
        'the chart',
        'the graph',
        'the figure',
        'coordinate plane',
        'shown in',
        'shown below',
        'shown above',
        'as shown',
        'illustrated in',
        'displayed in',
        'refers to the',
        'look at the'
      ]
      
      const mentionsDiagram = diagramPhrases.some(phrase => questionLower.includes(phrase))
      
      const hasImageUrl = !!question.imageUrl && question.imageUrl.length > 0
      const hasChartDescription = !!question.chartDescription && question.chartDescription.length > 10

      // CRITICAL ERROR: Question mentions diagram but has no image
      if (mentionsDiagram && !hasImageUrl) {
        console.log(`  ⚠️  CRITICAL: Question mentions diagram without image`)
        console.log(`     Question: "${question.question.substring(0, 60)}..."`)
        console.log(`     hasChart: ${question.hasChart}, imageUrl: ${hasImageUrl}, chartDesc: ${hasChartDescription}`)

        const newQualityScore = Math.max(0.3, question.qualityScore - 0.4) // -40% penalty

        return {
          ...question,
          qualityScore: newQualityScore,
          isAccepted: false,
          evaluationFeedback: `${question.evaluationFeedback} | CRITICAL ERROR: Question references diagram/chart that doesn't exist. Quality penalized from ${(question.qualityScore * 100).toFixed(0)}% to ${(newQualityScore * 100).toFixed(0)}%.`
        }
      }

      // ERROR: Has chart flag but no image generated
      if (question.hasChart && !hasImageUrl) {
        console.log(`  ⚠️  ERROR: Chart generation failed`)
        console.log(`     Question: "${question.question.substring(0, 60)}..."`)

        const newQualityScore = Math.max(0.4, question.qualityScore - 0.25) // -25% penalty

        return {
          ...question,
          qualityScore: newQualityScore,
          isAccepted: false,
          evaluationFeedback: `${question.evaluationFeedback} | ERROR: Chart/diagram generation failed. Quality penalized from ${(question.qualityScore * 100).toFixed(0)}% to ${(newQualityScore * 100).toFixed(0)}%.`
        }
      }

      // SUCCESS: Diagram mentioned and image exists
      if (mentionsDiagram && hasImageUrl) {
        console.log(`  ✅ Diagram consistency OK: "${question.question.substring(0, 60)}..."`)
      }

      return question
    })
  }

